// Package typegen generates the TypeScript `PluginConfig` module augmentation of a
// plugin (src/codi-env.d.ts) from its config.schema.json (`codi plugin typegen`).
//
// Optionality follows what plugins actually receive in ctx.config: the runtime applies
// schema defaults (config.ApplyDefaults) to the top-level object and, recursively, to
// nested objects — never inside arrays. So a property is non-optional when it is
// required, or when it has a default (or is an object that defaults materialize) and
// is reached from the root through object properties only. Inside array items only
// `required` makes a property non-optional.
//
// Types: string/number/integer/boolean/null map to their TypeScript types; enum and
// const become literal unions; x-codi-ref values are keys (string); arrays become T[];
// objects with properties become inline object types; additionalProperties schemas
// become Record<string, T>; oneOf/anyOf become unions; local $ref (#/$defs/…,
// #/definitions/…) are inlined. Anything else is `unknown`.
package typegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Header is the first line of a generated file.
const Header = "// Generated by `codi plugin typegen` from config.schema.json — do not edit."

const nestedNote = "// Fields with a default inside arrays are optional: the runtime applies defaults to\n// objects only; the plugin falls back on them itself."

// Generate returns the content of codi-env.d.ts for a JSON schema document. A nil
// schema (plugin without config) produces an empty PluginConfig.
func Generate(schemaJSON []byte) (string, error) {
	var schema map[string]any
	if len(schemaJSON) > 0 {
		v, err := decodeOrdered(schemaJSON)
		if err != nil {
			return "", fmt.Errorf("config schema: %w", err)
		}
		m, ok := v.(map[string]any)
		if !ok {
			return "", fmt.Errorf("config schema: not a JSON object")
		}
		schema = m
	}
	return GenerateFrom(schema), nil
}

// GenerateFrom is Generate for a decoded schema.
func GenerateFrom(schema map[string]any) string {
	g := &gen{root: schema}
	var body string
	if schema == nil {
		body = "  interface PluginConfig {}\n"
	} else {
		props := g.objectBody(schema, "    ", true, 0)
		if props == "" {
			body = "  interface PluginConfig {}\n"
		} else {
			body = "  interface PluginConfig {\n" + props + "  }\n"
		}
	}
	var b strings.Builder
	b.WriteString(Header + "\n")
	if g.nestedDefaults {
		b.WriteString(nestedNote + "\n")
	}
	b.WriteString("declare module \"@codi/sdk\" {\n")
	b.WriteString(body)
	b.WriteString("}\nexport {};\n")
	return b.String()
}

type gen struct {
	root map[string]any
	// nestedDefaults is set when a default inside an array item is ignored.
	nestedDefaults bool
}

const maxDepth = 32

// resolve follows a local $ref.
func (g *gen) resolve(s map[string]any, depth int) map[string]any {
	for i := 0; i < 8 && s != nil; i++ {
		ref, ok := s["$ref"].(string)
		if !ok {
			return s
		}
		target := g.pointer(ref)
		if target == nil {
			return map[string]any{}
		}
		// keep sibling keywords (2020-12 allows them next to $ref)
		merged := map[string]any{}
		for k, v := range target {
			merged[k] = v
		}
		for k, v := range s {
			if k != "$ref" {
				merged[k] = v
			}
		}
		s = merged
	}
	return s
}

func (g *gen) pointer(ref string) map[string]any {
	p, ok := strings.CutPrefix(ref, "#")
	if !ok {
		return nil
	}
	cur := any(g.root)
	for _, part := range strings.Split(strings.TrimPrefix(p, "/"), "/") {
		if part == "" {
			continue
		}
		part = strings.ReplaceAll(strings.ReplaceAll(part, "~1", "/"), "~0", "~")
		m, ok := cur.(map[string]any)
		if !ok {
			return nil
		}
		cur = m[part]
	}
	m, _ := cur.(map[string]any)
	return m
}

// materializes reports whether ApplyDefaults creates the object s when it is absent.
func materializes(s map[string]any) bool {
	if s["type"] != "object" {
		return false
	}
	_, props := propsOf(s)
	for _, raw := range props {
		sub, _ := raw.(map[string]any)
		if sub == nil {
			continue
		}
		if _, ok := sub["default"]; ok {
			return true
		}
		if materializes(sub) {
			return true
		}
	}
	return false
}

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func propName(k string) string {
	if identRe.MatchString(k) {
		return k
	}
	return strconv.Quote(k)
}

// objectBody renders the property lines of an object schema (each ending in "\n").
func (g *gen) objectBody(s map[string]any, indent string, defaultsApply bool, depth int) string {
	s = g.resolve(s, depth)
	keys, props := propsOf(s)
	required := map[string]bool{}
	if req, ok := s["required"].([]any); ok {
		for _, r := range req {
			if rs, ok := r.(string); ok {
				required[rs] = true
			}
		}
	}
	var b strings.Builder
	for _, k := range keys {
		sub, _ := props[k].(map[string]any)
		if sub == nil {
			sub = map[string]any{}
		}
		rs := g.resolve(sub, depth)
		_, hasDefault := rs["default"]
		optional := !required[k]
		if optional && defaultsApply && (hasDefault || materializes(rs)) {
			optional = false
		}
		if !defaultsApply && hasDefault && !required[k] {
			g.nestedDefaults = true
		}
		mark := ""
		if optional {
			mark = "?"
		}
		fmt.Fprintf(&b, "%s%s%s: %s;\n", indent, propName(k), mark, g.typeOf(rs, indent, defaultsApply, depth+1))
	}
	switch ap := s["additionalProperties"].(type) {
	case bool:
		if ap && len(keys) > 0 {
			fmt.Fprintf(&b, "%s[key: string]: unknown;\n", indent)
		}
	case map[string]any:
		if len(keys) > 0 {
			fmt.Fprintf(&b, "%s[key: string]: unknown;\n", indent)
		}
	}
	return b.String()
}

// orderKey holds the declaration order of an object's keys (see decodeOrdered).
const orderKey = "\x00order"

// propsOf returns the property names of an object schema, in declaration order when
// the schema was decoded by decodeOrdered (sorted otherwise), and the properties.
func propsOf(s map[string]any) ([]string, map[string]any) {
	props, _ := s["properties"].(map[string]any)
	if order, ok := props[orderKey].([]string); ok {
		return order, props
	}
	keys := make([]string, 0, len(props))
	for k := range props {
		if k != orderKey {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	return keys, props
}

// decodeOrdered decodes JSON like json.Unmarshal into any, recording the key order of
// every object under orderKey.
func decodeOrdered(data []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	v, err := decodeValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, fmt.Errorf("unexpected data after the JSON value")
	}
	return v, nil
}

func decodeValue(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			m := map[string]any{}
			var order []string
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return nil, err
				}
				k, _ := kt.(string)
				v, err := decodeValue(dec)
				if err != nil {
					return nil, err
				}
				if _, dup := m[k]; !dup {
					order = append(order, k)
				}
				m[k] = v
			}
			if _, err := dec.Token(); err != nil {
				return nil, err
			}
			m[orderKey] = order
			return m, nil
		case '[':
			out := []any{}
			for dec.More() {
				v, err := decodeValue(dec)
				if err != nil {
					return nil, err
				}
				out = append(out, v)
			}
			if _, err := dec.Token(); err != nil {
				return nil, err
			}
			return out, nil
		}
		return nil, fmt.Errorf("unexpected %v", t)
	default:
		return tok, nil
	}
}

func (g *gen) typeOf(s map[string]any, indent string, defaultsApply bool, depth int) string {
	if depth > maxDepth {
		return "unknown"
	}
	s = g.resolve(s, depth)
	if c, ok := s["const"]; ok {
		return literal(c)
	}
	if e, ok := s["enum"].([]any); ok && len(e) > 0 {
		parts := make([]string, 0, len(e))
		for _, v := range e {
			parts = append(parts, literal(v))
		}
		return strings.Join(dedupe(parts), " | ")
	}
	if _, ok := s["x-codi-ref"]; ok {
		if s["type"] == "array" {
			return "string[]"
		}
		return "string"
	}
	for _, kw := range []string{"oneOf", "anyOf"} {
		if alts, ok := s[kw].([]any); ok && len(alts) > 0 {
			var parts []string
			for _, a := range alts {
				am, _ := a.(map[string]any)
				if am == nil {
					continue
				}
				// alternatives inherit the parent's type when they do not set one
				if _, has := am["type"]; !has {
					if t, ok := s["type"]; ok {
						cp := map[string]any{"type": t}
						for k, v := range am {
							cp[k] = v
						}
						am = cp
					}
				}
				parts = append(parts, g.typeOf(am, indent, defaultsApply, depth+1))
			}
			if len(parts) > 0 {
				return strings.Join(dedupe(parts), " | ")
			}
		}
	}
	var types []string
	switch t := s["type"].(type) {
	case string:
		types = []string{t}
	case []any:
		for _, e := range t {
			if es, ok := e.(string); ok {
				types = append(types, es)
			}
		}
	}
	if len(types) == 0 {
		switch {
		case s["properties"] != nil:
			types = []string{"object"}
		case s["items"] != nil:
			types = []string{"array"}
		default:
			return "unknown"
		}
	}
	parts := make([]string, 0, len(types))
	for _, t := range types {
		parts = append(parts, g.single(t, s, indent, defaultsApply, depth))
	}
	return strings.Join(dedupe(parts), " | ")
}

func (g *gen) single(t string, s map[string]any, indent string, defaultsApply bool, depth int) string {
	switch t {
	case "string":
		return "string"
	case "number", "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		items, _ := s["items"].(map[string]any)
		if items == nil {
			return "unknown[]"
		}
		it := g.typeOf(items, indent, false, depth+1)
		if strings.Contains(it, " | ") && !strings.HasPrefix(it, "{") {
			it = "(" + it + ")"
		}
		return it + "[]"
	case "object":
		if keys, _ := propsOf(s); len(keys) == 0 {
			if ap, ok := s["additionalProperties"].(map[string]any); ok {
				return "Record<string, " + g.typeOf(ap, indent, false, depth+1) + ">"
			}
			return "Record<string, unknown>"
		}
		inner := indent + "  "
		return "{\n" + g.objectBody(s, inner, defaultsApply, depth+1) + indent + "}"
	}
	return "unknown"
}

func literal(v any) string {
	switch tv := v.(type) {
	case string:
		return strconv.Quote(tv)
	case nil:
		return "null"
	case bool:
		return strconv.FormatBool(tv)
	case float64:
		return strconv.FormatFloat(tv, 'g', -1, 64)
	case json.Number:
		return tv.String()
	}
	return "unknown"
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}
