package typegen

import (
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// RoutePlugin is one plugin of a repository as seen by the portal: its portal routes
// (from its definition) and, when it declares one, its route contract (plugin.yaml
// spec.routes.types).
type RoutePlugin struct {
	Name    string
	Version string
	// Source as written in bot.yaml (local path or <registry>/<name>), for the header.
	Source string
	Routes []Route
	// Contract is the content of the contract file ("" when the plugin declares none).
	Contract string
}

// Route is a portal route of a plugin.
type Route struct {
	Method, Path, Access string
}

// Key is the route key as written in the plugin ("GET /polls/:id").
func (r Route) Key() string { return r.Method + " " + r.Path }

// RoutesHeader starts every file written by GenerateRoutes.
const RoutesHeader = "// Code generated by `cicord portal typegen`. DO NOT EDIT."

// GenerateRoutes returns the TypeScript declaration file that types the plugin routes of a
// repository for @cicord/client and @cicord/react: a module augmentation of
// `PluginRouteRegistry`, keyed by plugin name then route key. Contracts are inlined in a
// namespace per plugin; routes of plugins without a contract are typed as untyped JSON.
// Plugins are sorted by name; a plugin listed twice must be identical.
func GenerateRoutes(plugins []RoutePlugin) (string, error) {
	byName := map[string]RoutePlugin{}
	for _, p := range plugins {
		if len(p.Routes) == 0 {
			continue
		}
		if prev, ok := byName[p.Name]; ok {
			if !sameRoutes(prev, p) {
				return "", fmt.Errorf("two different plugins are named %q (%s and %s): the portal types plugin routes by plugin name", p.Name, prev.Source, p.Source)
			}
			continue
		}
		if p.Contract != "" {
			if err := CheckRouteContract(p.Contract); err != nil {
				return "", fmt.Errorf("plugin %s: route contract: %w", p.Name, err)
			}
		}
		byName[p.Name] = p
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(RoutesHeader + "\n")
	b.WriteString("// Types of the portal routes of the plugins installed in the repository, for\n")
	b.WriteString("// @cicord/client (`client.routes(plugin, …)`) and @cicord/react (`useRouteQuery`,\n")
	b.WriteString("// `useRouteMutation`). `cicord portal build` regenerates it; see docs/portal.md.\n")
	if len(names) == 0 {
		b.WriteString("//\n// No plugin of the repository has portal routes.\n\nexport {};\n")
		return b.String(), nil
	}
	b.WriteString("//\n")
	for _, n := range names {
		p := byName[n]
		typed := "untyped (no spec.routes.types)"
		if p.Contract != "" {
			typed = "typed"
		}
		fmt.Fprintf(&b, "//   %s %s (%s): %d route(s), %s\n", p.Name, p.Version, p.Source, len(p.Routes), typed)
	}
	b.WriteString("\nimport type { RouteEntry } from \"@cicord/client\";\n")
	for _, n := range names {
		p := byName[n]
		if p.Contract == "" {
			continue
		}
		fmt.Fprintf(&b, "\n// Contract of %s (spec.routes.types), copied verbatim.\ndeclare namespace %s {\n", p.Name, namespaceOf(p.Name))
		for _, line := range strings.Split(strings.TrimRight(strings.ReplaceAll(p.Contract, "\r\n", "\n"), "\n"), "\n") {
			if strings.TrimSpace(line) == "" {
				b.WriteString("\n")
				continue
			}
			b.WriteString("  " + line + "\n")
		}
		b.WriteString("}\n")
	}
	b.WriteString("\ndeclare module \"@cicord/client\" {\n  interface PluginRouteRegistry {\n")
	for _, n := range names {
		p := byName[n]
		fmt.Fprintf(&b, "    %q: {\n", p.Name)
		routes := append([]Route(nil), p.Routes...)
		sort.Slice(routes, func(i, j int) bool { return routes[i].Key() < routes[j].Key() })
		for _, r := range routes {
			if p.Contract != "" {
				fmt.Fprintf(&b, "      %q: RouteEntry<%q, %s.Routes, %q>;\n", r.Key(), r.Access, namespaceOf(p.Name), r.Key())
			} else {
				fmt.Fprintf(&b, "      %q: RouteEntry<%q>;\n", r.Key(), r.Access)
			}
		}
		b.WriteString("    };\n")
	}
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

func namespaceOf(plugin string) string {
	return "cicord_" + strings.ReplaceAll(plugin, "-", "_")
}

func sameRoutes(a, b RoutePlugin) bool {
	if a.Contract != b.Contract || len(a.Routes) != len(b.Routes) {
		return false
	}
	ka, kb := map[Route]bool{}, map[Route]bool{}
	for i := range a.Routes {
		ka[a.Routes[i]], kb[b.Routes[i]] = true, true
	}
	for k := range ka {
		if !kb[k] {
			return false
		}
	}
	return true
}

var contractRoutes = regexp.MustCompile(`(?m)^\s*export\s+(interface\s+Routes\b|type\s+Routes\s*=)`)

// CheckRouteContract checks that a route contract can be copied into a portal: it must
// export `Routes` and contain only type declarations (`interface`, `type`), without
// imports, values or global declarations, so that it compiles on its own.
func CheckRouteContract(src string) error {
	top, err := topLevel(src)
	if err != nil {
		return err
	}
	if !contractRoutes.MatchString(top) {
		return errors.New("it must export `interface Routes` (or `type Routes = …`)")
	}
	for _, line := range strings.Split(top, "\n") {
		line = strings.TrimSpace(line)
		m := contractForbidden.FindStringSubmatch(line)
		if m == nil {
			m = contractReexport.FindStringSubmatch(line)
		}
		if m == nil {
			continue
		}
		if m[2] == "import" || m[2] == "require" || m[2] == "{" || m[2] == "*" {
			return fmt.Errorf("imports and re-exports are not allowed (%q): the file is copied into the portals and must be self-contained", firstLine(line))
		}
		return fmt.Errorf("only type declarations (interface, type) are allowed, found %q", firstLine(line))
	}
	return nil
}

// Top-level statements a contract may not contain: anything but `interface` and `type`
// declarations (continuation lines of a multi-line type never start with these words).
var (
	contractForbidden = regexp.MustCompile(`^(export\s+)?(import|require|default|const|let|var|function|class|enum|declare|namespace|module|abstract|async|global)\b`)
	contractReexport  = regexp.MustCompile(`^(export)\s*(\{|\*|=)`)
)

func firstLine(s string) string {
	s, _, _ = strings.Cut(s, "\n")
	if len(s) > 60 {
		s = s[:60] + "…"
	}
	return s
}

// topLevel returns src without comments, with the contents of (), [], {} and string or
// template literals blanked out, so that only top-level statements remain (one per line).
func topLevel(src string) (string, error) {
	var b strings.Builder
	depth := 0
	for i := 0; i < len(src); i++ {
		c := src[i]
		switch {
		case c == '/' && i+1 < len(src) && src[i+1] == '/':
			for i < len(src) && src[i] != '\n' {
				i++
			}
			if i < len(src) {
				b.WriteByte('\n')
			}
		case c == '/' && i+1 < len(src) && src[i+1] == '*':
			end := strings.Index(src[i+2:], "*/")
			if end < 0 {
				return "", errors.New("unterminated comment")
			}
			if strings.Contains(src[i:i+2+end], "\n") {
				b.WriteByte('\n')
			} else {
				b.WriteByte(' ')
			}
			i += end + 3
		case c == '"' || c == '\'' || c == '`':
			j := i + 1
			for j < len(src) && src[j] != c {
				if src[j] == '\\' {
					j++
				}
				j++
			}
			if j >= len(src) {
				return "", errors.New("unterminated string")
			}
			if depth == 0 {
				b.WriteString(`""`)
			}
			i = j
		case c == '{' || c == '(' || c == '[':
			if depth == 0 {
				b.WriteByte(c)
			}
			depth++
		case c == '}' || c == ')' || c == ']':
			depth--
			if depth < 0 {
				return "", errors.New("unbalanced brackets")
			}
			if depth == 0 {
				b.WriteByte(c)
				b.WriteByte('\n')
			}
		case depth == 0:
			if c == ';' {
				b.WriteString(";\n")
			} else {
				b.WriteByte(c)
			}
		}
	}
	if depth != 0 {
		return "", errors.New("unbalanced brackets")
	}
	return b.String(), nil
}
