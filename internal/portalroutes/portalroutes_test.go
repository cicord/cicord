package portalroutes

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/cicord/cicord/internal/config"
	"github.com/cicord/cicord/internal/version"
)

// The route types depend on the repository only: the same repository gives the same bytes
// (what `cicord portal typegen --check` compares), whatever cicord generates them.
func TestGenerateIsDeterministicAndVersionIndependent(t *testing.T) {
	root, err := filepath.Abs(filepath.Join("..", "..", "examples", "basic"))
	if err != nil {
		t.Fatal(err)
	}
	repo, ds := config.Load(root, config.LoadOptions{})
	if repo == nil || ds.HasErrors() {
		t.Fatalf("load: %v", ds.Errors())
	}
	first, err := Generate(repo)
	if err != nil {
		t.Fatal(err)
	}
	old := version.Version
	t.Cleanup(func() { version.Version = old })
	for _, v := range []string{"0.0.1", "9.9.9-rc.1"} {
		version.Version = v
		again, err := Generate(repo)
		if err != nil {
			t.Fatal(err)
		}
		if again != first {
			t.Fatalf("cicord %s generates other bytes:\n%s\nfirst:\n%s", v, again, first)
		}
		if strings.Contains(again, v) {
			t.Errorf("the route types name the cicord version %s", v)
		}
	}
	// The header names the plugin versions (what a Store update changes), nothing else.
	for _, want := range []string{
		"// Code generated by `cicord portal typegen`. DO NOT EDIT.\n",
		"//   onboarding 0.1.0 (../../plugins/onboarding): 2 route(s), untyped (no spec.routes.types)\n",
	} {
		if !strings.Contains(first, want) {
			t.Errorf("missing %q in\n%s", want, first)
		}
	}
	if keys := Keys(first); !keys["onboarding GET /steps"] || !keys["onboarding POST /complete"] || len(keys) != 2 {
		t.Errorf("keys = %v", keys)
	}
	if rel := Tracked(root, repo.Project); rel != "" {
		t.Errorf("examples/basic has no custom portal, Tracked = %q", rel)
	}
}
