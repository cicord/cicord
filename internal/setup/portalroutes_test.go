// portalRepo copies examples/basic with a custom portal (spec.portal.path ./portal/dist)
// whose sources have route types (content: the current file).
func portalRepo(t *testing.T, content string) string {
	t.Helper()
	dir := t.TempDir()
	if err := copyDir(filepath.Join("..", "..", "examples", "basic"), dir); err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(dir, "cicord.yaml")
	data, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	files := map[string]string{
		"cicord.yaml":                   strings.Replace(string(data), "spec:\n", "spec:\n  portal:\n    path: ./portal/dist\n", 1),
		"portal/package.json":           `{"name":"portal","private":true}`,
		"portal/dist/index.html":        "<!doctype html>",
		"portal/src/cicord-routes.d.ts": content,
	}
	for name, c := range files {
		f := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(f), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(f, []byte(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func loadRepo(t *testing.T, dir string) *config.Repo {
	t.Helper()
	repo, ds := config.Load(dir, config.LoadOptions{})
	if repo == nil || ds.HasErrors() {
		t.Fatalf("load: %v", ds.Errors())
	}
	return repo
}

func TestRegenerateRoutes(t *testing.T) {
	// A stale file is regenerated, the route the change removes is named.
	stale := "// Code generated by `cicord portal typegen`. DO NOT EDIT.\n" +
		"declare module \"@cicord/client\" {\n  interface PluginRouteRegistry {\n    \"onboarding\": {\n      \"GET /old\": RouteEntry<\"member\">;\n    };\n  }\n}\n"
	dir := portalRepo(t, stale)
	r := regenerateRoutes(dir, loadRepo(t, dir))
	if r.Path != "portal/src/cicord-routes.d.ts" || r.Content == nil || len(r.Warnings) != 0 ||
		!strings.Contains(string(r.Content), "//   onboarding 0.1.0 (../../plugins/onboarding): 2 route(s)") {
		t.Fatalf("regenerate = %+v\n%s", r, r.Content)
	}
	if len(r.Removed) != 1 || r.Removed[0] != "onboarding GET /old" {
		t.Errorf("removed = %v", r.Removed)
	}
	edits := map[string]writeback.EditFunc{}
	msg := r.apply(edits, "plugin(moderator): install x")
	if edits[r.Path] == nil || !strings.Contains(msg, "\n\nRegenerated portal/src/cicord-routes.d.ts (cicord portal typegen).") ||
		!strings.Contains(msg, "onboarding GET /old") {
		t.Errorf("apply: %q, edits %v", msg, editPaths(edits))
	}

	// Up to date: nothing to write.
	if err := os.WriteFile(filepath.Join(dir, "portal", "src", "cicord-routes.d.ts"), r.Content, 0o644); err != nil {
		t.Fatal(err)
	}
	if again := regenerateRoutes(dir, loadRepo(t, dir)); again.Content != nil || len(again.Warnings) != 0 {
		t.Errorf("up to date = %+v", again)
	}

	// No route types in the portal: left alone.
	if err := os.Remove(filepath.Join(dir, "portal", "src", "cicord-routes.d.ts")); err != nil {
		t.Fatal(err)
	}
	none := regenerateRoutes(dir, loadRepo(t, dir))
	edits = map[string]writeback.EditFunc{}
	if none.Path != "" || none.apply(edits, "m") != "m" || len(edits) != 0 {
		t.Errorf("without route types = %+v", none)
	}

	// Typegen fails (a route contract that cannot be read): the change goes on, and says so.
	dir = portalRepo(t, stale)
	m := filepath.Join(dir, "plugins", "onboarding", "plugin.yaml")
	data, err := os.ReadFile(m)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(m, []byte(strings.Replace(string(data), "  entry: ./src/index.ts\n", "  entry: ./src/index.ts\n  routes:\n    types: ./src/missing.ts\n", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	failed := regenerateRoutes(dir, loadRepo(t, dir))
	if failed.Content != nil || len(failed.Warnings) != 1 || !strings.Contains(failed.Warnings[0], "portal/src/cicord-routes.d.ts was not regenerated") ||
		!strings.Contains(failed.Warnings[0], "cicord portal typegen") {
		t.Fatalf("failed typegen = %+v", failed)
	}
	edits = map[string]writeback.EditFunc{}
	msg = failed.apply(edits, "plugin: update x")
	if len(edits) != 0 || !strings.Contains(msg, "\n\nWarning: portal/src/cicord-routes.d.ts was not regenerated") {
		t.Errorf("apply after a failure: %q", msg)
	}
}
