// Repository providers offered by the wizard.
const (
	// ProviderLocal writes the configuration into the directory `cicord dev` watches.
	ProviderLocal = "local"
	// ProviderEmbedded is the git repository managed by Cicord in the data dir.
	ProviderEmbedded = "embedded"
	// ProviderGitHub is a remote git repository (GitHub, or any HTTPS git remote).
	ProviderGitHub = "github"
)

// GitTokenSecret is the secret name of the git token (same as the environment variable).
const GitTokenSecret = gitauth.TokenSecret

// RepoConfig is where the configuration lives (persisted in the setup state so that a
// restart without cicord.yaml boots from it).
type RepoConfig struct {
	Provider string `json:"provider"`
	// URL is the remote of the github provider.
	URL    string `json:"url,omitempty"`
	Branch string `json:"branch"`
	// Dir is the watched directory (local) or the bare repository (embedded).
	Dir string `json:"dir,omitempty"`
	// TokenRef names the git token secret (github, personal access token).
	TokenRef string `json:"tokenRef,omitempty"`
	// Auth is how the github provider authenticates: gitauth.MethodToken (also when
	// empty, states written before GitHub Apps) or gitauth.MethodApp (the
	// CICORD_GITHUB_APP_* secrets).
	Auth string `json:"auth,omitempty"`
}

// GitHubRepo returns "owner/name" for a github.com URL ("" otherwise).
func GitHubRepo(remote string) string {
	s := strings.TrimSuffix(remote, ".git")
	u, err := url.Parse(s)
	if err != nil || !strings.EqualFold(u.Host, "github.com") {
		return ""
	}
	parts := strings.Split(strings.Trim(u.Path, "/"), "/")
	if len(parts) != 2 {
		return ""
	}
	return parts[0] + "/" + parts[1]
}

// RepoFiles are the inputs of the generated repository.
type RepoFiles struct {
	Project       string
	ServerKey     string
	ServerYAML    []byte
	BotKey        string
	ApplicationID string
	SecretRef     string
	Repo          RepoConfig
	PublicURL     string
}

// engineRange returns the default engine constraint for new repos/plugins: the current minor.
func engineRange() string { return version.EngineRange(version.Version) }

var projectTmpl = template.Must(template.New("cicord.yaml").Parse(`# Generated by the Cicord setup wizard.
apiVersion: cicord.dev/v1alpha1
kind: Project
metadata:
  name: {{.Project}}
spec:
  engine: "{{.Engine}}"
{{- if .Provider}}
  source:
    provider: {{.Provider}}
{{- if .URL}}
    repo: {{.URL}}
{{- end}}
    branch: {{.Branch}}
{{- end}}
{{- if .PublicURL}}
  runtime:
    url: {{.PublicURL}}
{{- end}}
  writeBack:
{{- if eq .Provider "github"}}
    # Plugin settings and installs are committed directly; structural changes
    # (roles, channels, permissions) open a pull request for review.
    defaultMode: pullRequest
    policies:
      - paths: ["bots/**", "plugins/**"]
        mode: commit
      - paths: ["servers/**"]
        mode: pullRequest
{{- else}}
    # Every change made in the admin UI is a commit (history in the admin UI).
    defaultMode: commit
{{- end}}
`))

var botTmpl = template.Must(template.New("bot.yaml").Parse(`# Generated by the Cicord setup wizard.
apiVersion: cicord.dev/v1alpha1
kind: Bot
metadata:
  name: {{.BotKey}}
spec:
  applicationId: "{{.ApplicationID}}"
  token:
    # Stored encrypted by the runtime (secret store); an environment variable with this
    # name takes precedence.
    secretRef: {{.SecretRef}}
  servers: [{{.ServerKey}}]
  # ServerMessages lets Cicord see that messages arrive (setup verification) and is
  # needed by most plugins. It is not a privileged intent.
  intents: [ServerMessages]
  plugins: []
`))

const readme = `# %s

Discord server configuration managed by [Cicord](https://github.com/cicord/cicord),
generated by the setup wizard.

- ` + "`servers/%s.yaml`" + ` — roles, channels and permissions of the server
- ` + "`bots/%s/bot.yaml`" + ` — the bot and its plugins
- ` + "`plugins/`" + ` — installed plugins

Every change made in the admin UI is a commit in this repository.

` + "```bash" + `
cicord validate     # check the configuration
cicord plan         # show what would change on Discord
` + "```" + `
`

// Generate renders the repository files.
func (in RepoFiles) Generate() (map[string][]byte, error) {
	provider, u := "", ""
	switch in.Repo.Provider {
	case ProviderEmbedded:
		provider = "embedded"
	case ProviderGitHub:
		provider, u = "github", in.Repo.URL
		if GitHubRepo(in.Repo.URL) == "" {
			provider = "git"
		}
	}
	branch := in.Repo.Branch
	if branch == "" {
		branch = "main"
	}
	var proj bytes.Buffer
	err := projectTmpl.Execute(&proj, map[string]any{"Project": in.Project, "Engine": engineRange(), "Provider": provider,
		"URL": u, "Branch": branch, "PublicURL": in.PublicURL})
	if err != nil {
		return nil, err
	}
	// "git" uses the same writeBack block as "github" minus PRs: commit everything.
	projText := proj.String()
	if provider == "git" {
		projText = strings.Replace(projText, "defaultMode: pullRequest", "defaultMode: commit", 1)
	}
	var bot bytes.Buffer
	if err := botTmpl.Execute(&bot, in); err != nil {
		return nil, err
	}
	return map[string][]byte{
		"cicord.yaml":                       []byte(projText),
		"servers/" + in.ServerKey + ".yaml": in.ServerYAML,
		"bots/" + in.BotKey + "/bot.yaml":   bot.Bytes(),
		".gitignore":                        []byte(".cicord/\n*.db\n*.db-*\n.env\nnode_modules/\n"),
		"README.md":                         []byte(fmt.Sprintf(readme, in.Project, in.ServerKey, in.BotKey)),
	}, nil
}

// keepExisting adapts the generated files to a non-empty target: an existing README.md
// is kept, missing lines are appended to an existing .gitignore. The generated
// configuration files are never in conflict (cicord.yaml is checked beforehand).
func keepExisting(dir string, files map[string][]byte) map[string][]byte {
	out := make(map[string][]byte, len(files))
	for k, v := range files {
		out[k] = v
	}
	if _, err := os.Stat(filepath.Join(dir, "README.md")); err == nil {
		delete(out, "README.md")
	}
	if cur, err := os.ReadFile(filepath.Join(dir, ".gitignore")); err == nil {
		have := map[string]bool{}
		for _, l := range strings.Split(string(cur), "\n") {
			have[strings.TrimSpace(l)] = true
		}
		merged := strings.TrimRight(string(cur), "\n") + "\n"
		added := false
		for _, l := range strings.Split(strings.TrimSpace(string(files[".gitignore"])), "\n") {
			if l = strings.TrimSpace(l); l != "" && !have[l] {
				if !added {
					merged += "# Cicord\n"
					added = true
				}
				merged += l + "\n"
			}
		}
		if added {
			out[".gitignore"] = []byte(merged)
		} else {
			delete(out, ".gitignore")
		}
	}
	return out
}

func writeTree(dir string, files map[string][]byte) error {
	for rel, data := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

var cicordSig = func() *object.Signature {
	return &object.Signature{Name: "cicord[bot]", Email: "cicord[bot]@users.noreply.github.com", When: time.Now()}
}

// CheckRemote verifies that a remote is reachable with the credentials (nil: anonymous).
// It returns whether the remote is empty and whether it already contains a Cicord
// configuration on branch.
func CheckRemote(ctx context.Context, remoteURL, branch string, tokens gitauth.TokenSource) (empty, hasCicord bool, err error) {
	auth, err := gitauth.GitAuth(ctx, tokens)
	if err != nil {
		return false, false, err
	}
	rem := git.NewRemote(memory.NewStorage(), &gitconfig.RemoteConfig{Name: "origin", URLs: []string{remoteURL}})
	refs, err := rem.ListContext(ctx, &git.ListOptions{Auth: auth})
	if errors.Is(err, transport.ErrEmptyRemoteRepository) {
		return true, false, nil
	}
	if err != nil {
		return false, false, err
	}
	if len(refs) == 0 {
		return true, false, nil
	}
	// Look for cicord.yaml on the branch (shallow clone in memory).
	found := false
	for _, r := range refs {
		if r.Name() == plumbing.NewBranchReferenceName(branch) {
			found = true
		}
	}
	if !found {
		return false, false, nil
	}
	repo, err := git.CloneContext(ctx, memory.NewStorage(), nil, &git.CloneOptions{URL: remoteURL, Auth: auth,
		ReferenceName: plumbing.NewBranchReferenceName(branch), SingleBranch: true, Depth: 1, NoCheckout: true})
	if err != nil {
		return false, false, err
	}
	head, err := repo.Head()
	if err != nil {
		return false, false, err
	}
	c, err := repo.CommitObject(head.Hash())
	if err != nil {
		return false, false, err
	}
	if _, err := c.File("cicord.yaml"); err == nil {
		return false, true, nil
	}
	return false, false, nil
}

// InitRepository writes the files as the first commit of the configuration repository
// and returns the commit SHA ("" for the local provider).
//   - local: files are written into cfg.Dir (which must not contain cicord.yaml);
//   - embedded: a bare repository is created at cfg.Dir (it must not exist);
//   - github: the remote is cloned (or initialized when empty), the files are committed
//     on cfg.Branch and pushed. A remote that already contains cicord.yaml is refused.
func InitRepository(ctx context.Context, cfg RepoConfig, tokens gitauth.TokenSource, files map[string][]byte, message string) (string, error) {
	branch := cfg.Branch
	if branch == "" {
		branch = "main"
	}
	switch cfg.Provider {
	case ProviderLocal:
		if _, err := os.Stat(filepath.Join(cfg.Dir, "cicord.yaml")); err == nil {
			return "", fmt.Errorf("%s already contains a cicord.yaml", cfg.Dir)
		}
		return "", writeTree(cfg.Dir, keepExisting(cfg.Dir, files))
	case ProviderEmbedded:
		if _, err := git.PlainOpen(cfg.Dir); err == nil {
			return "", fmt.Errorf("the embedded repository %s already exists", cfg.Dir)
		}
		work, err := os.MkdirTemp("", "cicord-setup-*")
		if err != nil {
			return "", err
		}
		defer os.RemoveAll(work)
		r, err := git.PlainInitWithOptions(work, &git.PlainInitOptions{InitOptions: git.InitOptions{DefaultBranch: plumbing.NewBranchReferenceName(branch)}})
		if err != nil {
			return "", err
		}
		sha, err := commitAll(r, work, files, message)
		if err != nil {
			return "", err
		}
		if _, err := git.PlainCloneContext(ctx, cfg.Dir, true, &git.CloneOptions{URL: work}); err != nil {
			return "", err
		}
		return sha, nil
	case ProviderGitHub:
		work, err := os.MkdirTemp("", "cicord-setup-*")
		if err != nil {
			return "", err
		}
		defer os.RemoveAll(work)
		auth, err := gitauth.GitAuth(ctx, tokens)
		if err != nil {
			return "", err
		}
		empty, hasCicord, err := CheckRemote(ctx, cfg.URL, branch, tokens)
		if err != nil {
			return "", err
		}
		if hasCicord {
			return "", errors.New("this repository already contains a Cicord configuration (cicord.yaml): pick an empty repository, or run `cicord serve` with it")
		}
		var r *git.Repository
		if !empty {
			// Build on the branch when it exists (README, LICENSE…).
			r, err = git.PlainCloneContext(ctx, work, false, &git.CloneOptions{URL: cfg.URL, Auth: auth,
				ReferenceName: plumbing.NewBranchReferenceName(branch), SingleBranch: true})
			if err != nil {
				// The branch does not exist yet: start it from scratch in a clean directory.
				if err := os.RemoveAll(work); err != nil {
					return "", err
				}
				if err := os.MkdirAll(work, 0o700); err != nil {
					return "", err
				}
				r = nil
			}
		}
		if r == nil {
			if r, err = git.PlainInitWithOptions(work, &git.PlainInitOptions{InitOptions: git.InitOptions{DefaultBranch: plumbing.NewBranchReferenceName(branch)}}); err != nil {
				return "", err
			}
			if _, err := r.CreateRemote(&gitconfig.RemoteConfig{Name: "origin", URLs: []string{cfg.URL}}); err != nil {
				return "", err
			}
		}
		sha, err := commitAll(r, work, keepExisting(work, files), message)
		if err != nil {
			return "", err
		}
		if auth, err = gitauth.GitAuth(ctx, tokens); err != nil { // renewed token after a slow clone
			return "", err
		}
		po := &git.PushOptions{RemoteName: "origin", Auth: auth,
			RefSpecs: []gitconfig.RefSpec{gitconfig.RefSpec(fmt.Sprintf("refs/heads/%s:refs/heads/%s", branch, branch))}}
		if err := r.PushContext(ctx, po); err != nil && !errors.Is(err, git.NoErrAlreadyUpToDate) {
			return "", fmt.Errorf("push: %w", err)
		}
		return sha, nil
	}
	return "", fmt.Errorf("unknown repository provider %q", cfg.Provider)
}

func commitAll(r *git.Repository, work string, files map[string][]byte, message string) (string, error) {
	if err := writeTree(work, files); err != nil {
		return "", err
	}
	wt, err := r.Worktree()
	if err != nil {
		return "", err
	}
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		if _, err := wt.Add(p); err != nil {
			return "", err
		}
	}
	sig := cicordSig()
	h, err := wt.Commit(strings.TrimSpace(message)+"\n\nCicord-Source: setup\n", &git.CommitOptions{Author: sig, Committer: sig})
	if err != nil {
		return "", err
	}
	return h.String(), nil
}
