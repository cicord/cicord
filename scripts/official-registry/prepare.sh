#!/usr/bin/env bash
# Generates the content of github.com/cicord/cicord-plugins, the official plugin registry: a
# monorepo with plugins/<name>/ (tags <name>/v<version>) and index.yaml at its root.
#
#   scripts/official-registry/prepare.sh <out-dir>
#
# The plugins come from examples/ (the copies bundled in the cicord binary), with a
# standalone tsconfig.json (SDK types from .cicord/, written by `cicord plugin sdk-types`),
# their unit tests and plugin-files/<name>/ extras; the rest from template/. <out-dir> must
# not exist. The script builds cicord and the @cicord/sdk tarball (vendor/, the unit tests'
# dependency), installs the npm dev dependencies (pnpm-lock.yaml), then makes <out-dir> a git
# repository: a commit with everything, `cicord plugin publish` for each plugin (local tags
# <name>/v<version>, entries in index.yaml) and a commit with the index.
#
# Nothing is pushed and nothing is signed: generating the signing key, the secret, the first
# signature and the push are the owner's steps (docs/plugins.md §9). Push the result as is,
# tags included: index.yaml pins the commits of these tags.
#
# Environment: CICORD (an existing cicord binary instead of building one), PNPM (default
# pnpm), GO (default go).
set -euo pipefail

registry_url="https://github.com/cicord/cicord-plugins"
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
out="${1:?usage: scripts/official-registry/prepare.sh <out-dir>}"
PNPM="${PNPM:-pnpm}"
GO="${GO:-go}"
if [[ -e "$out" ]]; then
  echo "$out already exists: pass a new directory" >&2
  exit 1
fi
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cicord="${CICORD:-}"
if [[ -z "$cicord" ]]; then
  echo "• building cicord"
  (cd "$root" && "$GO" build -o "$tmp/cicord" ./cmd/cicord)
  cicord="$tmp/cicord"
fi
echo "• packing @cicord/sdk"
(cd "$root/packages/sdk" && "$PNPM" run build >/dev/null 2>&1 && "$PNPM" pack --pack-destination "$tmp" >/dev/null)
sdk_tgz="$(cd "$tmp" && ls cicord-sdk-*.tgz)"

mkdir -p "$out"
out="$(cd "$out" && pwd)"
cp -R "$here/template/." "$out/"
mv "$out/gitignore" "$out/.gitignore"
mv "$out/node-version" "$out/.node-version"
mv "$out/dot-github" "$out/.github"
while IFS= read -r f; do mv "$f" "${f%.tmpl}"; done < <(find "$out" -name '*.tmpl')
cp "$root/LICENSE" "$out/LICENSE"
mkdir -p "$out/vendor"
cp "$tmp/$sdk_tgz" "$out/vendor/"
sed -i.bak "s|@SDK_SPEC@|file:vendor/$sdk_tgz|" "$out/package.json" && rm "$out/package.json.bak"

# The official plugins, in catalog order (examples/catalog.go).
plugins=()
table=""
while IFS= read -r src; do
  name="$(basename "$src")"
  plugins+=("$name")
  from="$root/examples/$src"
  dest="$out/plugins/$name"
  mkdir -p "$dest"
  cp "$from/plugin.yaml" "$from/config.schema.json" "$dest/"
  # The schema comment points into the Cicord repository: use its published URL.
  sed -i.bak 's|^# yaml-language-server: \$schema=.*/spec/schemas/plugin.schema.json$|# yaml-language-server: $schema=https://raw.githubusercontent.com/cicord/cicord/main/spec/schemas/plugin.schema.json|' "$dest/plugin.yaml"
  rm "$dest/plugin.yaml.bak"
  cp -R "$from/src" "$dest/src"
  cp "$here/plugin-files/tsconfig.json" "$dest/tsconfig.json"
  if [[ -d "$from/test" ]]; then
    cp -R "$from/test" "$dest/test"
    cp "$here/plugin-files/test.tsconfig.json" "$dest/test/tsconfig.json"
  fi
  if [[ -d "$here/plugin-files/$name" ]]; then
    cp -R "$here/plugin-files/$name/." "$dest/"
  fi
  "$cicord" plugin typegen "$dest" --check >/dev/null
  description="$(awk '/^  description: / { sub(/^  description: /, ""); print; exit }' "$dest/plugin.yaml")"
  table+="| [\`$name\`](plugins/$name) | $description |"$'\n'
done < <(grep -oE '"[a-z]+/plugins/[a-z0-9-]+"' "$root/examples/catalog.go" | tr -d '"')
printf '%s' "$table" > "$tmp/table.md"
awk -v table="$tmp/table.md" '$0 == "@PLUGIN_TABLE@" { while ((getline line < table) > 0) print line; next } { print }' \
  "$out/README.md" > "$tmp/README.md"
mv "$tmp/README.md" "$out/README.md"

echo "• installing the dev dependencies (pnpm-lock.yaml)"
(cd "$out" && "$PNPM" install --silent)

cicord_rev="$(cd "$root" && git rev-parse --short HEAD)"
cd "$out"
git init -q -b main
git add -A
git commit -q -m "feat: import the official Cicord plugins

From github.com/cicord/cicord $cicord_rev (examples/, the copies bundled in the binary),
generated by scripts/official-registry/prepare.sh."

for name in "${plugins[@]}"; do
  "$cicord" plugin publish "plugins/$name" --registry . --repo "$registry_url" --publisher Cicord >/dev/null
  echo "• published $name ($(git describe --tags --abbrev=0 --match "$name/v*"))"
done
# The official plugins are published by the Cicord project: a verified publisher.
awk '{ print } /^    publisher: Cicord$/ { print "    verified: true" }' index.yaml > "$tmp/index.yaml"
mv "$tmp/index.yaml" index.yaml
git add index.yaml
git commit -q -m "index: publish the official plugins"

cat <<MSG

Prepared $out (branch main, $(git rev-list --count HEAD) commits, $(git tag | wc -l | tr -d ' ') tags). Not pushed, not signed.
Check it:   cd $out && PATH="$(dirname "$cicord"):\$PATH" bash scripts/check-all.sh
Then the owner steps of docs/plugins.md §9 (keygen, keys/official.pub, secrets, push with tags, sign).
MSG
